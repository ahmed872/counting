# Qt ignores margins on tables, so every table-based block is followed by a
# small empty paragraph to keep it from touching whatever comes next.
GAP = "<p style='margin:0; font-size:5pt;'>&nbsp;</p>"
PAGE_BREAK = "<p style='page-break-before: always; margin:0; font-size:1pt;'>&nbsp;</p>"


def section(num, title):
    return (
        f"{GAP}<table width='100%' cellspacing='0' cellpadding='8'>"
        f"<tr><td style='background:{NAVY}; color:#ffffff; font-size:14pt; font-weight:bold;'>"
        f"{num}. {title}</td></tr></table>{GAP}"
    )


def sub(title):
    return f"<h3>{title}</h3>"


def table(rows, left="الزر / الخانة", right="وظيفته", left_width=30):
    body = "".join(
        f"<tr><td class='k' width='{left_width}%'>{name}</td><td>{what}</td></tr>"
        for name, what in rows
    )
    return (
        f"<table width='100%' cellspacing='0' cellpadding='6' border='1' "
        f"style='border-color:{LINE}; border-style:solid; border-collapse:collapse;'>"
        f"<tr><th align='right'>{left}</th><th align='right'>{right}</th></tr>{body}</table>{GAP}"
    )


