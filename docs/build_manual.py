def load_fonts():
    for name in FONT_FILES:
        path = os.path.join(HERE, "fonts", name)
        if not os.path.exists(path):
            raise SystemExit(f"[خطأ] ملف الخط غير موجود: {path}")
        font_id = QFontDatabase.addApplicationFont(path)
        if font_id < 0 or FAMILY not in QFontDatabase.applicationFontFamilies(font_id):
            raise SystemExit(f"[خطأ] تعذّر تحميل الخط: {path}")


def check_fonts(path):
    """Qt substitutes a fallback font without a word when a glyph or a family
    is missing. Any font in the PDF other than the bundled one means that
    happened somewhere, so the file is thrown away rather than shipped."""
    with open(path, "rb") as handle:
        blob = handle.read()
    names = {
        name.decode("latin-1").split("+")[-1]
        for name in re.findall(rb"/BaseFont\s*/([A-Za-z0-9+_.-]+)", blob)
    }
    strangers = sorted(n for n in names if not n.startswith("IBMPlexSansArabic"))
    if not names or strangers:
        os.remove(path)
        raise SystemExit(f"[خطأ] الدليل استخدم خطاً غير الخط المرفق: {strangers or 'لا شيء'}")


def _footer_option(alignment):
    option = QTextOption(alignment | Qt.AlignmentFlag.AlignAbsolute | Qt.AlignmentFlag.AlignVCenter)
    option.setTextDirection(Qt.LayoutDirection.RightToLeft)
    return option


def build():
    app = QApplication.instance() or QApplication(sys.argv)  # noqa: F841
    load_fonts()

    document = QTextDocument()
    document.setDefaultFont(QFont(FAMILY, 10))
    document.setDefaultStyleSheet(CSS)
    option = document.defaultTextOption()
    option.setTextDirection(Qt.LayoutDirection.RightToLeft)
    document.setDefaultTextOption(option)
    document.setHtml(HTML)

    printer = QPrinter(QPrinter.PrinterMode.HighResolution)
    printer.setOutputFormat(QPrinter.OutputFormat.PdfFormat)
    printer.setOutputFileName(OUTPUT)
    # An explicit page size, never the default printer's - see save_pdf in
    # ui/reports_module.py for the blank-page bug that comes from relying on it.
    printer.setPageLayout(QPageLayout(
        QPageSize(QPageSize.PageSizeId.A4), QPageLayout.Orientation.Portrait,
        QMarginsF(16, 14, 16, 12), QPageLayout.Unit.Millimeter))
    printer.setDocName(TITLE)

    # Paginated by hand rather than document.print() so every page gets a
    # footer with the page number. Laying the text out against the printer
    # (not the screen) is what keeps 10pt at 10pt in the PDF.
    area = printer.pageRect(QPrinter.Unit.DevicePixel)
    footer_height = 24.0 * printer.resolution() / 72.0
    document.documentLayout().setPaintDevice(printer)
    body = QSizeF(area.width(), area.height() - footer_height)
    document.setPageSize(body)
    pages = document.pageCount()

    painter = QPainter(printer)
    footer_font = QFont(FAMILY, 8)
    for index in range(pages):
        if index:
            printer.newPage()
        painter.save()
        painter.translate(0, -index * body.height())
        context = QAbstractTextDocumentLayout.PaintContext()
        context.clip = QRectF(0, index * body.height(), body.width(), body.height())
        painter.setClipRect(context.clip)
        document.documentLayout().draw(painter, context)
        painter.restore()

        line_y = body.height() + footer_height * 0.3
        painter.setPen(QColor(LINE))
        painter.drawLine(0, int(line_y), int(body.width()), int(line_y))
        painter.setPen(QColor("#7b8a9b"))
        painter.setFont(footer_font)
        strip = QRectF(0, line_y, body.width(), footer_height * 0.7)
        painter.drawText(strip, TITLE, _footer_option(Qt.AlignmentFlag.AlignRight))
        painter.drawText(strip, f"صفحة {index + 1} من {pages}", _footer_option(Qt.AlignmentFlag.AlignLeft))
    painter.end()

    check_fonts(OUTPUT)
    size = os.path.getsize(OUTPUT)
    print(f"تم إنشاء الدليل: {OUTPUT}  ({pages} صفحة، {size:,} بايت)")
    return OUTPUT


if __name__ == "__main__":
    build()
