def contents_table():
    """Two columns of sections side by side, so the whole cover fits on page 1."""
    half = (len(CONTENTS) + 1) // 2

    def cells(number):
        if number > len(CONTENTS):
            return "<td width='7%'></td><td width='43%'></td>"
        return (f"<td width='7%' align='center' style='color:{NAVY}; font-weight:bold;'>{number}</td>"
                f"<td width='43%'>{CONTENTS[number - 1]}</td>")

    rows = "".join(f"<tr>{cells(i)}{cells(i + half)}</tr>" for i in range(1, half + 1))
    return (
        f"<table width='100%' cellspacing='0' cellpadding='5' border='1' "
        f"style='border-color:{LINE}; border-style:solid; border-collapse:collapse;'>{rows}</table>{GAP}"
    )


